# evaluates a polynomial at the matrix B
def matrix_polynomial(B, coeffs):
    I = np.eye(B.shape[0])
    result = coeffs[0] * I
    B_power = I

    for coeff in coeffs[1:]:
        B_power = B_power @ B
        result = result + coeff * B_power

    return result


