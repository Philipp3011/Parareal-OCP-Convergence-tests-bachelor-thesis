gamma_SDIRK22 = (2.0 - np.sqrt(2.0)) / 2.0


def R_SDIRK22(B):
    I = np.eye(B.shape[0])
    Q = I + gamma_SDIRK22 * B

    return (I + (2.0 * gamma_SDIRK22 - 1.0) * B) @ solve(Q @ Q, I)


def P1_SDIRK22(B):
    I = np.eye(B.shape[0])
    Q = I + gamma_SDIRK22 * B

    return (1.0 - gamma_SDIRK22) * solve(Q @ Q, I)


def P2_SDIRK22(B):
    I = np.eye(B.shape[0])
    Q = I + gamma_SDIRK22 * B

