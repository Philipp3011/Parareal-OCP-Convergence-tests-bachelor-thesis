# maximum L2-error for two FEM-functions defined with mass matrix
def L2_for_FEM(U1, U2, mass):
    errors = []
    for u1, u2 in zip(U1, U2):
        e = u1 - u2
        errors.append(np.sqrt(e.T @ mass @ e))
    return max(errors)


