def matrix_from_scalar_function(phi, delta_T, eigenvalues, eigenvectors, eigenvectors_inverse):
  values = np.asarray(phi(delta_T * eigenvalues), dtype=np.float64)
  return (eigenvectors * values) @ eigenvectors_inverse


